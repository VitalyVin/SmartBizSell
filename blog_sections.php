function blogSectionBySlug(string $slug): ?array {
    $sections = blogSections();
    if (!isset($sections[$slug])) {
        return null;
    }
    $section = $sections[$slug];
    $section['slug'] = $slug;
    if (!isset($section['match'])) {
        $section['match'] = [$section['title']];
    }
    return $section;
}

/**
 * @return array{slug:?string,topic:string}
 */
function blogResolveCategory(string $category): array {
    $category = trim($category);
    if ($category === '') {
        return ['slug' => null, 'topic' => ''];
    }

    foreach (blogSections() as $slug => $section) {
        $roots = $section['match'] ?? [$section['title']];
        foreach ($roots as $root) {
            $prefix = $root . ' / ';
            if ($category === $root) {
                $topic = ($root === $section['title']) ? '' : $root;
                return ['slug' => $slug, 'topic' => $topic];
            }
            if (str_starts_with($category, $prefix)) {
                return ['slug' => $slug, 'topic' => trim(substr($category, strlen($prefix)))];
            }
        }
    }

    return ['slug' => null, 'topic' => ''];
}

function blogCategoryLabel(string $category): string {
    $resolved = blogResolveCategory($category);
    if ($resolved['topic'] !== '') {
        return $resolved['topic'];
    }
    if ($resolved['slug'] !== null) {
        return blogSections()[$resolved['slug']]['title'];
    }
    return $category;
}

function blogListUrl(?string $sectionSlug = null, array $query = []): string {
    $path = $sectionSlug ? '/blog/razdel/' . rawurlencode($sectionSlug) : '/blog';
    $clean = [];
    foreach (['topic', 'search', 'page'] as $key) {
        if (!array_key_exists($key, $query) || $query[$key] === null || $query[$key] === '') {
            continue;
        }
        if ($key === 'page' && (int)$query[$key] <= 1) {
            continue;
        }
        $clean[$key] = $query[$key];
    }
    $qs = http_build_query($clean);
    return $path . ($qs !== '' ? '?' . $qs : '');
}

function blogCategoryLikePrefix(string $root): string {
    $escaped = str_replace(['\\', '%', '_'], ['\\\\', '\\%', '\\_'], $root);
    return $escaped . ' / %';
}
